#!/usr/bin/env python3
"""Offline runner regression: real detached layout, arbitrary paths/cwd, failures."""
import hashlib
import json
import os
from pathlib import Path
import subprocess
import sys
import tempfile
import unittest
from unittest.mock import patch

from ProcChildren import children

RUNNER = Path(__file__).resolve().parents[1] / 'scripts/m20-g3-reproduce.py'


class ProcessObservation(unittest.TestCase):
    def test_actual_child_and_reap_with_optional_proc_file_missing(self):
        process = subprocess.Popen([sys.executable, '-c', 'import time; time.sleep(60)'])
        read = Path.read_text

        def without_children(path, *args, **kwargs):
            if path.name == 'children':
                raise FileNotFoundError(str(path))
            return read(path, *args, **kwargs)

        try:
            self.assertIn(process.pid, children(os.getpid()))
            with patch.object(Path, 'read_text', without_children):
                self.assertIn(process.pid, children(os.getpid()))
                process.terminate()
                process.wait(timeout=5)
                self.assertNotIn(process.pid, children(os.getpid()))
        finally:
            if process.poll() is None:
                process.kill()
            process.wait(timeout=5)

    def test_unreadable_process_observation_fails_closed(self):
        def unreadable(path, *args, **kwargs):
            if path.name == 'children':
                raise FileNotFoundError(str(path))
            raise PermissionError(str(path))

        with patch.object(Path, 'read_text', unreadable):
            with self.assertRaises(PermissionError):
                children(os.getpid())


class Reproduce(unittest.TestCase):
    def setUp(self):
        self.temp = tempfile.TemporaryDirectory(prefix='g3 runner tests ')
        self.root = Path(self.temp.name)
        self.repo, self.stage, self.bundle = [self.root / name for name in ('source', 'stage', 'bundle')]
        for path in (self.repo, self.stage, self.bundle):
            path.mkdir()
        frontend = self.repo / 'src/admin/frontend'
        frontend.mkdir(parents=True)
        (frontend / 'package-lock.json').write_text('{}')
        (frontend / 'node_modules').mkdir()
        (frontend / 'node_modules/preprovisioned').write_text('fixture')
        (self.repo / '.gitignore').write_text('/src/admin/frontend/node_modules/\n/src/admin/frontend/.test-build/\n')
        subprocess.run(['git', 'init', '-q', str(self.repo)], check=True)
        subprocess.run(['git', '-C', str(self.repo), 'add', '.'], check=True)
        subprocess.run(['git', '-C', str(self.repo), '-c', 'user.name=Offline Fixture', '-c', 'user.email=fixture@invalid',
                        'commit', '-q', '-m', 'synthetic offline fixture'], check=True)
        self.head = subprocess.check_output(['git', '-C', str(self.repo), 'rev-parse', 'HEAD'], text=True).strip()
        subprocess.run(['git', '-C', str(self.repo), 'checkout', '-q', '--detach', self.head], check=True)
        (self.stage / 'dependency').write_text('prepared')
        sha = lambda p: hashlib.sha256(p.read_bytes()).hexdigest()
        (self.bundle / 'FINAL-HEAD.txt').write_text(self.head)
        (self.bundle / 'environment.json').write_text(json.dumps({'source_head': self.head,
            'dependency_hashes': {'dependency': sha(self.stage / 'dependency')},
            'frontend_lock_sha256': sha(frontend / 'package-lock.json')}))
        private = self.bundle / 'historical-store'
        private.mkdir(mode=0o700)
        (private / 'snapshot.json').write_text('{}')
        (private / 'snapshot.json').chmod(0o600)
        (self.bundle / 'acceptance.py').write_text('''from pathlib import Path
import subprocess,sys
E=Path(__file__).resolve().parent
R=E.parent.parent/'m20-g3-worktree'
assert Path.cwd()==E.parent.parent
assert not R.is_symlink() and (R/'.git').is_dir()
assert (E/'historical-store').stat().st_mode&0o7777==0o700
assert (E/'historical-store/snapshot.json').stat().st_mode&0o7777==0o600
assert (R/'src/admin/frontend/node_modules/preprovisioned').read_text()=='fixture'
assert subprocess.check_output(['git','-C',str(R),'rev-parse','--abbrev-ref','HEAD'],text=True).strip()=='HEAD'
# Generated by acceptance, without manually staging a .test-build directory.
p=R/'src/admin/frontend/.test-build';p.mkdir();(p/'generated').write_text('ok')
subprocess.run([sys.executable,str(E/'nested.py')],cwd=E,check=True)
''')
        (self.bundle / 'nested.py').write_text('import pathlib\nassert pathlib.Path("nested.py").is_file()\n')
        self.manifest()
        self.cwd = self.root / 'unrelated cwd'
        self.cwd.mkdir()

    def manifest(self):
        files = {n: hashlib.sha256((self.bundle / n).read_bytes()).hexdigest() for n in ('acceptance.py', 'nested.py', 'historical-store/snapshot.json')}
        (self.bundle / 'harness-input-manifest.json').write_text(json.dumps({'files': files, 'directories': {'historical-store': 0o700}}))

    def tearDown(self):
        self.temp.cleanup()

    def run_runner(self, output):
        return subprocess.run([sys.executable, str(RUNNER), '--repo', str(self.repo), '--stage', str(self.stage),
            '--bundle', str(self.bundle), '--output', str(output)], cwd=self.cwd,
            stdout=subprocess.PIPE, stderr=subprocess.STDOUT, text=True, timeout=15)

    def test_real_detached_layout_from_arbitrary_cwd_and_new_output(self):
        output = self.root / 'arbitrary new output'
        result = self.run_runner(output)
        self.assertEqual(result.returncode, 0, result.stdout)
        self.assertIn('G3_AGGREGATE_PASS', result.stdout)
        self.assertTrue((output / 'm20-g3-worktree/src/admin/frontend/.test-build/generated').is_file())
        self.assertEqual(subprocess.check_output(['git', '-C', str(self.repo), 'status', '--porcelain'], text=True), '')
        # Existing evidence must be preserved, never reused or overwritten.
        self.assertNotEqual(self.run_runner(output).returncode, 0)

    def test_nested_subprocess_failure_is_final_failure(self):
        (self.bundle / 'nested.py').write_text('raise SystemExit(7)\n')
        self.manifest()
        result = self.run_runner(self.root / 'failed output')
        self.assertNotEqual(result.returncode, 0)
        self.assertNotIn('G3_AGGREGATE_PASS', result.stdout)
        self.assertIn('non-zero exit status 7', result.stdout)

    def test_source_and_dependency_tampering_fails_before_output(self):
        (self.stage / 'dependency').write_text('changed')
        output = self.root / 'tampered output'
        result = self.run_runner(output)
        self.assertNotEqual(result.returncode, 0)
        self.assertIn('dependency hash mismatch', result.stdout)
        self.assertFalse(output.exists())


if __name__ == '__main__':
    unittest.main()
